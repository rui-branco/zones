param([switch]$RegenerateIcon, [string]$OutDir = "bin")

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$src  = Join-Path $root "src"
$obj  = Join-Path $root "obj"
$csc  = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe"

# -OutDir builds somewhere else than bin, which a running bin\zones.exe keeps
# locked. A relative one is taken from here, as the default is.
if (-not [System.IO.Path]::IsPathRooted($OutDir)) { $OutDir = Join-Path $root $OutDir }

if (-not (Test-Path $csc)) { throw "csc.exe not found at $csc" }
if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }
if (-not (Test-Path $obj)) { New-Item -ItemType Directory -Path $obj | Out-Null }

$out = Join-Path $OutDir "zones.exe"
$files = Get-ChildItem $src -Filter *.cs -Recurse | ForEach-Object { $_.FullName }

# The one version number, shared with the Mac app and the release script, is
# ..\VERSION. It goes into the exe from a generated file under obj\, so nothing
# committed repeats it, and the updater compares releases against it.
$versionFile = Join-Path $root "..\VERSION"
if (-not (Test-Path $versionFile)) { throw "VERSION not found at $versionFile" }
$version = "$(Get-Content $versionFile -Raw)".Trim()
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw "VERSION must read X.Y.Z, not '$version'" }

$versionCs = Join-Path $obj "Version.g.cs"
Set-Content -Path $versionCs -Encoding ASCII -Value @(
  "// Generated by build.ps1 from ..\VERSION. Edit that, not this.",
  "using System.Reflection;",
  "",
  "[assembly: AssemblyVersion(""$version.0"")]",
  "[assembly: AssemblyFileVersion(""$version.0"")]",
  "[assembly: AssemblyInformationalVersion(""$version"")]"
)

# Generate the icon if it is missing, so a clean checkout still builds branded.
# The artwork is src\Ui\Logo.cs, the same drawing as the settings window's title
# bar; IconGen renders it and refreshes the README logo in ..\docs too.
# -RegenerateIcon forces a rebuild after the mark changes.
$ico = Join-Path $root "assets\zones.ico"
if ($RegenerateIcon -or -not (Test-Path $ico)) {
  Write-Host "Generating icon..."
  $assets = Join-Path $root "assets"
  $docs = Join-Path $root "..\docs"
  foreach ($dir in @($obj, $assets, $docs)) {
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
  }
  $gen = Join-Path $obj "IconGen.exe"

  $genArgs = @(
    "/nologo",
    "/target:exe",
    "/optimize+",
    "/out:$gen",
    "/reference:System.Drawing.dll",
    (Join-Path $root "tools\IconGen.cs"),
    (Join-Path $src "Ui\Logo.cs")
  )
  & $csc $genArgs
  if ($LASTEXITCODE -ne 0) { throw "ICON FAILED (csc exit $LASTEXITCODE)" }

  & $gen $ico (Join-Path $docs "logo.png")
  if ($LASTEXITCODE -ne 0) { throw "ICON FAILED (IconGen exit $LASTEXITCODE)" }
}

$args = @(
  "/nologo",
  "/target:winexe",
  "/platform:anycpu",
  "/optimize+",
  "/win32icon:$ico",
  "/out:$out",
  "/reference:System.dll",
  "/reference:System.Core.dll",
  "/reference:System.Drawing.dll",
  "/reference:System.Windows.Forms.dll"
) + $files + $versionCs

Write-Host "Compiling $($files.Count) files..."
& $csc $args
if ($LASTEXITCODE -ne 0) { throw "BUILD FAILED (csc exit $LASTEXITCODE)" }

if (-not (Test-Path $out)) { throw "BUILD FAILED: $out was not produced" }
$size = (Get-Item $out).Length
Write-Host "BUILD OK -> $out (Zones $version, $size bytes)"
